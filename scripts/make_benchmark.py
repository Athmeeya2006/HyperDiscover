#!/usr/bin/env python
"""Generate benchmark files + a datasheet from an experiment grid.

python scripts/make_benchmark.py --grid configs/experiment/grid_reduced.yaml --out benchmarks_out
python scripts/make_benchmark.py --grid ... --list            # print instances (for SLURM arrays)
python scripts/make_benchmark.py --grid ... --index $SLURM_ARRAY_TASK_ID
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import git_commit  # noqa: E402


def instances(grid: dict) -> list[dict]:
    out = []
    variants = (
        [False, True]
        if grid.get("pairwise_only_variants")
        else [bool(grid.get("pairwise_only", False))]
    )
    for sid, kind, N, noise, seed, po in itertools.product(
        grid["systems"], grid["hyper_kinds"], grid["N"], grid["noise"], grid["seeds"], variants
    ):
        if po and kind != grid["hyper_kinds"][0]:
            continue  # pairwise-only variants do not depend on the hyperedge type
        out.append(
            {
                "system_id": sid,
                "hyper_kind": kind,
                "N": N,
                "noise": noise,
                "seed": seed,
                "pairwise_only": po,
                "graph": grid.get("graph", "er"),
                "mean_degree": grid.get("mean_degree", 4.0),
                "hyper_density": grid.get("hyper_density", 0.3),
                "M": grid.get("M", 50),
                "T": grid.get("T", 200),
                "kick_std": grid.get("kick_std", 0.0),
                "kick_every": grid.get("kick_every", 0),
                "ic_mode": grid.get("ic_mode", "uniform"),
            }
        )
    return out


def name_of(inst: dict) -> str:
    """Unique, readable name: every field of the instance spec appears (no silent collisions
    between grids that differ in graph, degree, density, M or T)."""
    po = "_pw" if inst["pairwise_only"] else f"_{inst['hyper_kind']}"
    return (
        f"{inst['system_id']}{po}_N{inst['N']}_noise{inst['noise']:g}_seed{inst['seed']}"
        f"_{inst['graph']}k{inst['mean_degree']:g}d{inst['hyper_density']:g}_M{inst['M']}T{inst['T']}"
        # data-design options: suffix only when non-default, so v0.1 names are unchanged
        + (f"_kick{inst['kick_std']:g}e{inst['kick_every']}" if inst.get("kick_std", 0) else "")
        + (f"_ic{inst['ic_mode']}" if inst.get("ic_mode", "uniform") != "uniform" else "")
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--grid", required=True)
    ap.add_argument("--out", default="benchmarks_out")
    ap.add_argument("--index", type=int, default=None)
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    grid = yaml.safe_load(Path(a.grid).read_text())
    insts = instances(grid)
    if a.list:
        for q, inst in enumerate(insts):
            print(q, name_of(inst))
        print(f"# {len(insts)} instances")
        return
    from hyperdiscover import benchmarks

    out = Path(a.out)
    todo = [insts[a.index]] if a.index is not None else insts
    rows = []
    for inst in todo:
        path = out / f"{name_of(inst)}.h5"
        if not path.exists():
            b = benchmarks.load(
                inst["system_id"],
                N=inst["N"],
                noise=inst["noise"],
                hyper_kind=inst["hyper_kind"],
                graph=inst["graph"],
                mean_degree=inst["mean_degree"],
                hyper_density=inst["hyper_density"],
                pairwise_only=inst["pairwise_only"],
                M=inst["M"],
                T=inst["T"],
                seed=inst["seed"],
                kick_std=inst.get("kick_std", 0.0),
                kick_every=inst.get("kick_every", 0),
                ic_mode=inst.get("ic_mode", "uniform"),
            )
            benchmarks.save(b, path)
            spec = b.spec
        else:
            spec = benchmarks.load_file(path)[1]
        rows.append({"file": path.name, **spec})
        print("wrote", path)
    if a.index is None:
        sheet = out / "DATASHEET.md"
        lines = [
            f"# Benchmark datasheet ({benchmarks.BENCH_VERSION})",
            "",
            f"Generated by `scripts/make_benchmark.py --grid {a.grid}` at commit `{git_commit()}`.",
            "Every instance is reproducible from its spec (system, N, noise, hyperedge type, seed).",
            "",
            "S5 is a synthetic variant designed for this benchmark. Hyperedge closure: open = no internal",
            "pairwise edges, closed = all three, mixed = a mixture of 0–3 internal edges.",
            "",
            "| file | system | N | edges | hyperedges | kind | pairwise-only | noise | M | T | dt | seed |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for r in rows:
            lines.append(
                f"| {r['file']} | {r['system_id']} | {r['N']} | {r['n_edges']} | {r['n_hyper']} | "
                f"{'–' if r['pairwise_only'] else r['hyper_kind']} | {r['pairwise_only']} | {r['noise']} | {r['M']} | {r['T']} | {r['dt']} | {r['seed']} |"
            )
        sheet.write_text("\n".join(lines) + "\n")
        (out / "index.json").write_text(json.dumps(rows, indent=1, default=float))
        print("wrote", sheet)


if __name__ == "__main__":
    main()
